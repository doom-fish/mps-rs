#[test]
fn image_batch_helpers_smoke() {
    let device = MetalDevice::system_default().expect("no Metal device available");
    let queue = device.new_command_queue().expect("command queue");
    let descriptor = ImageDescriptor {
        channel_format: feature_channel_format::FLOAT32,
        width: 2,
        height: 2,
        feature_channels: 1,
        number_of_images: 1,
        usage: texture_usage::SHADER_READ | texture_usage::SHADER_WRITE,
        storage_mode: storage_mode::SHARED,
    };
    let image = Image::new(&device, descriptor).expect("image");
    let _ = apple_mps::image::get_image_type(&image);
    let _ = apple_mps::image::image_batch_increment_read_count(&[&image, &image], 1);
    assert!(apple_mps::image::image_batch_resource_size(&[&image, &image]) > 0);
    let command_buffer = queue.new_command_buffer().expect("command buffer");
    apple_mps::image::image_batch_synchronize(&[&image, &image], &command_buffer);
    command_buffer.commit();
    command_buffer.wait_until_completed();
    let visit_count = apple_mps::image::image_batch_iterate(&[&image, &image], |_, index| {
        isize::try_from(index).expect("batch index fits in isize")
    });
    assert_eq!(visit_count, 0);
    let no_clip = apple_mps::core::rect_no_clip();
    assert_eq!(no_clip.x, 0);
    assert_eq!(no_clip.y, 0);
    assert_eq!(no_clip.z, 0);
}
